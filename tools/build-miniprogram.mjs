// Generate miniprogram/core/engine.js from the <script> in index.html.
// The web page stays the single source for lessons, quizzes, ranges, drills,
// the poker engine and the coach. Functions that only draw the web page are left
// out; when the shared code calls one of them, the call is forwarded to the
// mini program's own UI (env.UI). Run after every change to index.html:
//   npm install && npm run build:mp
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';
import * as acorn from 'acorn';
import * as walk from 'acorn-walk';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');
const m = html.match(/<script>([\s\S]*?)<\/script>/);
if (!m) throw new Error('no <script> in index.html');
const src = m[1];
const ast = acorn.parse(src, {ecmaVersion: 'latest'});
const iife = ast.body[0];
const fn = iife && iife.expression && iife.expression.callee;
if (!fn || !fn.body || fn.body.type !== 'BlockStatement') throw new Error('expected the script to be one (()=>{...})() block');

// web-only code: page rendering, DOM event wiring, the Claude account sync
const DROP = new Set(`toast toastT renderCourse startQuiz renderBanner HEAD renderTrackBar setTrack renderChips openDrill dStats
  newSpot answer tabs showTab drawStages calcM buildSliders icmDraw pays rLog rUI btns rStart rDeal rAct rEnd rBust rNext
  openSimPlay renderCashCard aiChat aiNotReady aiThread renderScnPick renderSim renderSimStatus renderActions showCoach
  showSimEnd renderAISettings initAISettings renderAll initSync pushSync setSync`.split(/\s+/).filter(Boolean));
// small replacements that behave better inside WeChat
const OVERRIDE = {
  fmt: "const fmt=n=>String(Math.round(n)).replace(/\\B(?=(\\d{3})+(?!\\d))/g,',');",
};

const names = st => {
  if (st.type === 'FunctionDeclaration') return [{n: st.id.name, kind: 'function'}];
  if (st.type === 'VariableDeclaration') return st.declarations.filter(d => d.id.type === 'Identifier').map(d => ({n: d.id.name, kind: st.kind}));
  return [];
};
const refs = node => {
  const s = new Set();
  walk.full(node, n => { if (n.type === 'Identifier') s.add(n.name); });
  return s;
};

const kept = [], dropped = new Map(), decl = [];
for (const st of fn.body.body) {
  const ns = names(st), code = src.slice(st.start, st.end);
  if (ns.length) {
    if (ns.some(x => DROP.has(x.n))) {
      if (ns.some(x => !DROP.has(x.n))) throw new Error('statement mixes kept and dropped names: ' + ns.map(x => x.n).join(','));
      ns.forEach(x => dropped.set(x.n, x.kind));
      continue;
    }
    const o = ns.length === 1 && OVERRIDE[ns[0].n];
    kept.push(o || code);
    decl.push(...ns);
    continue;
  }
  // top-level statements without a name: keep data setup, drop DOM wiring and boot calls
  const r = refs(st);
  if (/\$\(|document\.|addEventListener|location\./.test(code) || [...r].some(x => DROP.has(x))) continue;
  kept.push(code);
}

// calls from kept code into dropped functions go to env.UI
const used = new Set();
kept.forEach(code => { const r = refs(acorn.parse(code, {ecmaVersion: 'latest'})); r.forEach(x => { if (dropped.has(x)) used.add(x); }); });
const stubs = [...used].sort().map(n => {
  if (dropped.get(n) !== 'function') throw new Error(`kept code uses dropped non-function "${n}"`);
  return `function ${n}(...a){const f=UI.${n};return f?f(...a):undefined}`;
});
const unknown = Object.keys(OVERRIDE).filter(k => !decl.some(d => d.n === k));
if (unknown.length) throw new Error('override targets not found: ' + unknown.join(','));

const exp = decl.map(({n, kind}) => kind === 'let' ? `get ${n}(){return ${n}},set ${n}(v){${n}=v}` : `get ${n}(){return ${n}}`);
const out = `/* GENERATED by tools/build-miniprogram.mjs from index.html. Do not edit by hand: change index.html and run npm run build:mp. */
const env=require('./env.js');
const {document,localStorage,matchMedia,window,location,UI}=env;
${stubs.join('\n')}
${kept.join('\n')}
module.exports={${exp.join(',\n')}};
`;
writeFileSync(join(root, 'miniprogram/core/engine.js'), out);
console.log(`engine.js: ${kept.length} statements kept, ${dropped.size} web-only names left out, ${stubs.length} UI hooks (${[...used].sort().join(', ')}), ${(out.length / 1024).toFixed(0)} KB`);
